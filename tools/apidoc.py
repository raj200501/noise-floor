#!/usr/bin/env python3
"""Generate the evalstats API reference (docs/api/evalstats.md) from docstrings.

Lists every public name of `evalstats` and `evalstats.adapters` with its signature and
docstring, in module order. Run with `make apidoc` after changing the public API.
"""

from __future__ import annotations

import importlib
import inspect
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
OUT = REPO / "docs" / "api" / "evalstats.md"
MODULES = ("evalstats", "evalstats.adapters")


def describe(name: str, obj: object) -> list[str]:
    lines = []
    if inspect.isclass(obj):
        try:
            sig = str(inspect.signature(obj))
        except (TypeError, ValueError):
            sig = "(...)"
        lines += [f"### class `{name}{sig}`", "", inspect.getdoc(obj) or "", ""]
        for attr, member in inspect.getmembers(obj):
            if attr.startswith("_") or not (
                inspect.isfunction(member) or isinstance(member, property)
            ):
                continue
            doc = inspect.getdoc(member) or ""
            if isinstance(member, property):
                lines.append(f"- property `{attr}`: {doc.splitlines()[0] if doc else ''}")
            else:
                lines.append(
                    f"- `{attr}{inspect.signature(member)}`: {doc.splitlines()[0] if doc else ''}"
                )
        lines.append("")
    elif callable(obj):
        lines += [f"### `{name}{inspect.signature(obj)}`", "", inspect.getdoc(obj) or "", ""]
    else:
        lines += [f"### `{name}`", "", f"Value: `{obj!r}`", ""]
    return lines


def render() -> str:
    lines = [
        "# evalstats API reference",
        "",
        "Generated by `tools/apidoc.py` from the package's docstrings and signatures "
        "(`make apidoc`); do not edit by hand.",
        "",
    ]
    for mod_name in MODULES:
        module = importlib.import_module(mod_name)
        lines += [f"## `{mod_name}`", "", inspect.getdoc(module) or "", ""]
        for name in getattr(module, "__all__", []):
            lines += describe(name, getattr(module, name))
    return "\n".join(lines).rstrip() + "\n"


def main() -> int:
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(render())
    print(f"wrote {OUT.relative_to(REPO)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
