"""Leaderboard confidence reports (``docs/leaderboards/<board>.md``), generated from artifacts.

Every number in a report is read from ``artifacts/e2/<board>/results.json`` and
``manifest.json``; nothing is typed by hand. Wording is neutral: the report states
which orderings are and are not statistically supported and never explains why an
entry scored as it did.
"""

from __future__ import annotations

import json
from collections.abc import Mapping
from pathlib import Path
from typing import Any

REPO = Path(__file__).resolve().parents[3]
TITLES = {
    "tb2": "Terminal-Bench 2.0 submissions",
    "epoch-swebench": "SWE-bench Verified (Epoch AI Benchmarking Hub)",
}


def _f(x: Any, digits: int = 3) -> str:
    return "n/a" if x is None else f"{float(x):.{digits}f}"


def _signed(x: Any) -> str:
    return "n/a" if x is None else f"{float(x):+.3f}"


def render(board: str, results: Mapping[str, Any], manifest: Mapping[str, Any]) -> str:
    """The Markdown confidence report for one board."""
    primary = results["sets"]["primary"]
    q1, q2, q3 = primary["q1"], primary["q2"], primary["q3"]
    pct = round(100 * results["sets"]["primary"]["level"])
    source = manifest.get("source_url", "")
    pin = manifest.get("revision") or f"archive sha256 {manifest.get('archive_sha256', '')}"
    lines = [
        f"# Confidence report: {TITLES.get(board, board)}",
        "",
        "Generated by `python -m noisefloor.reanalysis report` from "
        f"`artifacts/e2/{board}/results.json`; analysis plan `{results['prereg']}`"
        + (f", amended by `{results['amendment']}`" if results.get("amendment") else "")
        + ".",
        "",
        f"- Source: {source} ({manifest.get('license', '')}), pinned at {pin}, "
        f"retrieved {manifest.get('retrieved', '')}.",
        f"- Snapshot: `{manifest.get('snapshot', '')}` (sha256 `{manifest.get('sha256', '')}`).",
        f"- Reference scoring rule: {results['reference_policy']}.",
        f"- Entries analyzed: {primary['n_entries']}; tasks used for rank intervals: "
        f"{q2['n_tasks']}.",
        "",
        "## Summary",
        "",
        f"- Adjacent pairs whose {pct}% paired interval excludes zero: {q1['n_supported']} of "
        f"{q1['n_pairs']} ({_f(q1['share_supported'])}); the board is "
        f"{q1['label']} by the preregistered threshold.",
        f"- Simultaneous {pct}% rank intervals: median width {_f(q2['median_width'], 1)} "
        f"ranks; {q2['n_could_be_first']} entries could be first.",
        f"- Policy sensitivity: {q3['n_identified']} of {q3['n_pairs']} adjacent orderings hold "
        f"under every way of scoring ambiguous runs, {q3['n_robust']} also with sampling "
        f"error; {q3['ranking_changes']} of 4 scoring policies change the ranking.",
        "",
        "## Entries",
        "",
        f"| Rank | Entry | Score [{pct}% CI] | Rank interval | Board pooled score |",
        "|---:|---|---|---|---:|",
    ]
    intervals = {r["entry"]: r for r in q2["intervals"]}
    for i, e in enumerate(primary["entries"], 1):
        r = intervals.get(e["entry"], {})
        lines.append(
            f"| {i} | {e['entry']} | {_f(e['score'])} [{_f(e['lo'])}, {_f(e['hi'])}] | "
            f"[{r.get('best', 'n/a')}, {r.get('worst', 'n/a')}] | {_f(e.get('pooled_score'))} |"
        )
    lines += [
        "",
        "## Adjacent pairs",
        "",
        f"| Higher | Lower | Difference [{pct}% CI] | Supported |",
        "|---|---|---|---|",
    ]
    for p in q1["pairs"]:
        lines.append(
            f"| {p['higher']} | {p['lower']} | {_signed(p['difference'])} "
            f"[{_signed(p['lo'])}, {_signed(p['hi'])}] | {'yes' if p['supported'] else 'no'} |"
        )
    lines += [
        "",
        "## Policy bounds",
        "",
        "Scores when ambiguous runs (infrastructure errors, timeouts, flagged runs) are kept as "
        "recorded, counted as failures, counted as successes, or dropped, and the worst-case "
        f"bounds with their {pct}% interval.",
        "",
        "| Entry | As recorded | Fail | Success | Exclude | Bounds | Interval |",
        "|---|---:|---:|---:|---:|---|---|",
    ]
    for b in q3["entries"]:
        lines.append(
            f"| {b['entry']} | {_f(b['score_as_scored'])} | {_f(b['score_fail'])} | "
            f"{_f(b['score_success'])} | {_f(b['score_exclude'])} | "
            f"[{_f(b['lower'])}, {_f(b['upper'])}] | [{_f(b['ci_lo'])}, {_f(b['ci_hi'])}] |"
        )
    excluded = results.get("excluded_entries", {})
    if excluded:
        lines += ["", "## Excluded entries", ""]
        lines += [f"- {name}: {why}." for name, why in sorted(excluded.items())]
    lines += [
        "",
        "## Reading this report",
        "",
        "An ordering is supported when the paired interval for the score difference, over the "
        "tasks both entries attempted, excludes zero. A rank interval covers every rank the "
        "entry could hold given the simultaneous comparisons with all other entries. Intervals "
        "describe sampling uncertainty over tasks and runs; they say nothing about why an entry "
        "scored as it did.",
        "",
    ]
    return "\n".join(lines)


def write_reports(boards: tuple[str, ...]) -> list[Path]:
    """Render and write the reports for the given boards."""
    paths = []
    for board in boards:
        base = REPO / "artifacts" / "e2" / board
        results = json.loads((base / "results.json").read_text())
        manifest = json.loads((base / "manifest.json").read_text())
        path = REPO / "docs" / "leaderboards" / f"{board}.md"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(render(board, results, manifest))
        paths.append(path)
    return paths
